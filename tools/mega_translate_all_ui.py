def translate_text(key: str, en_text: str, cn_text: str) -> str:
    """Translates a single UIText string into Vietnamese."""
    stripped_en = en_text.strip()
    
    # 1. Exact match in our comprehensive dictionary
    if stripped_en in EXACT_DICT:
        return EXACT_DICT[stripped_en]
    
    # 2. Chinese exact match fallback
    stripped_cn = cn_text.strip() if cn_text else ""
    if stripped_cn in CN_MAPPING:
        return CN_MAPPING[stripped_cn]
    
    # 3. Pattern match
    for pat, repl in PATTERNS:
        if pat.match(stripped_en):
            return pat.sub(repl, stripped_en)
            
    # 4. Keyword replacement for short strings (< 50 chars)
    # Check if string starts with "Tap to " or "Select "
    if stripped_en.startswith("Tap to "):
        action = stripped_en[7:]
        if action in EXACT_DICT:
            return f"Chạm để {EXACT_DICT[action].lower()}"
    if stripped_en.startswith("Tap "):
        action = stripped_en[4:]
        if action in EXACT_DICT:
            return f"Chạm {EXACT_DICT[action].lower()}"

    # Return en_text if no high-confidence translation rule matches
    return en_text


