def polish_story_item(item):
    k = item['key']
    en = item['en']
    vi = item['vi_current']

    if k in STORY_POLISH:
        return STORY_POLISH[k]

    # Global terminology and style cleanups
    vi = vi.replace('Lữ khách', 'Lữ Khách')
    vi = vi.replace('trại trẻ mồ côi', 'cô nhi viện')
    vi = vi.replace('vùng hoang dã', 'Vùng Hoang Dã')
    vi = vi.replace('Cự tháp', 'Cự Tháp')
    vi = vi.replace('Stellaroid', 'Tinh Hài')
    vi = vi.replace('Đóng mạng', 'Thập Diện Bủa Lưới')
    vi = vi.replace('Mã danh dự', 'Nhân Nghĩa & Lưỡi Đao')
    vi = vi.replace('chấn thương', 'Bóng Đen Tâm Lý')
    vi = vi.replace('vĩnh cửu', 'Vĩnh Cửu')
    vi = vi.replace('phản tác dụng', 'Phản Tác Dụng')
    vi = vi.replace('đồng hành', 'Bạn Đồng Hành')

    return vi

