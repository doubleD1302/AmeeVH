def main():
    names = json.load(open(INPUT_PATH, encoding="utf-8"))
    print(f"Loaded {len(names)} skill names.")

    translated = {}
    missing = []

    for name, info in names.items():
        if name in CURATED:
            translated[name] = CURATED[name]
        else:
            missing.append((name, info.get("cn", "")))

    print(f"Curated: {len(translated)} / {len(names)}")
    if missing:
        print(f"Missing {len(missing)} names:")
        for en, cn in missing:
            print(f"  {en} <-> {cn}")

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(translated, f, ensure_ascii=False, indent=2)

    print(f"Saved {len(translated)} translations to {OUTPUT_PATH.name}")

if __name__ == "__main__":
    main()
